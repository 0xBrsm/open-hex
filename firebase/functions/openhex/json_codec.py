def _event_to_json(e: Event) -> dict:
    d: dict[str, Any] = {"type": e.type}
    if e.player is not None:
        d["player"] = e.player.value
    if e.vertex:
        d["vertex"] = _vertex_to_json(e.vertex)
    if e.vertices:
        d["vertices"] = [_vertex_to_json(e.vertices[0]), _vertex_to_json(e.vertices[1])]
    if e.die1 is not None:
        d["die1"] = e.die1
    if e.die2 is not None:
        d["die2"] = e.die2
    if e.resources:
        d["resources"] = _resource_map_to_json(e.resources)
    if e.resource:
        d["resource"] = e.resource.value
    if e.dice_total is not None:
        d["diceTotal"] = e.dice_total
    if e.production:
        d["production"] = {c.value: _resource_map_to_json(rm) for c, rm in e.production.items()}
    if e.card:
        d["card"] = e.card.value
    if e.location:
        d["location"] = _hex_to_json(e.location)
    if e.target:
        d["target"] = e.target.value
    if e.partner:
        d["partner"] = e.partner.value
    if e.trade_id is not None:
        d["tradeId"] = e.trade_id
    if e.offering:
        d["offering"] = _resource_map_to_json(e.offering)
    if e.requesting:
        d["requesting"] = _resource_map_to_json(e.requesting)
    if e.collected:
        d["collected"] = {c.value: n for c, n in e.collected.items() if n != 0}
    if e.resource_list:
        d["resources"] = [r.value for r in e.resource_list]
    if e.length is not None:
        d["length"] = e.length
    if e.knights is not None:
        d["knights"] = e.knights
    if e.turn_number is not None:
        d["turnNumber"] = e.turn_number
    if e.victory_points is not None:
        d["victoryPoints"] = e.victory_points
    return d


