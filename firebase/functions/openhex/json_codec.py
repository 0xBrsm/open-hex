def _action_to_json(a: Action) -> dict:
    d: dict[str, Any] = {"type": a.type, "player": a.player.value}
    if a.vertex:
        d["vertex"] = _vertex_to_json(a.vertex)
    if a.vertices:
        d["vertices"] = [_vertex_to_json(a.vertices[0]), _vertex_to_json(a.vertices[1])]
    if a.location:
        d["location"] = _hex_to_json(a.location)
    if a.target:
        d["target"] = a.target.value
    if a.partner:
        d["partner"] = a.partner.value
    if a.resource:
        d["resource"] = a.resource.value
    if a.resources is not None:
        if isinstance(a.resources, list):
            d["resources"] = [r.value for r in a.resources]
        else:
            d["resources"] = _resource_map_to_json(a.resources)
    if a.trade_id is not None:
        d["tradeId"] = a.trade_id
    if a.offering:
        d["offering"] = _resource_map_to_json(a.offering)
    if a.requesting:
        d["requesting"] = _resource_map_to_json(a.requesting)
    return d


def _action_from_json(d: dict) -> Action:
    resources = None
    if "resources" in d:
        if isinstance(d["resources"], list):
            resources = [Resource(r) for r in d["resources"]]
        else:
            resources = _resource_map_from_json(d["resources"])

    vertices = None
    if "vertices" in d:
        vertices = (_vertex_from_json(d["vertices"][0]), _vertex_from_json(d["vertices"][1]))

    return Action(
        type=d["type"],
        player=PlayerColor(d["player"]),
        vertex=_vertex_from_json(d["vertex"]) if d.get("vertex") else None,
        vertices=vertices,
        location=_hex_from_json(d["location"]) if d.get("location") else None,
        target=PlayerColor(d["target"]) if d.get("target") else None,
        partner=PlayerColor(d["partner"]) if d.get("partner") else None,
        resource=Resource(d["resource"]) if d.get("resource") else None,
        resources=resources,
        trade_id=d.get("tradeId"),
        offering=_resource_map_from_json(d["offering"]) if d.get("offering") else None,
        requesting=_resource_map_from_json(d["requesting"]) if d.get("requesting") else None,
    )


