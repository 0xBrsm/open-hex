def _tile_to_json(t: Tile) -> dict:
    d: dict[str, Any] = {"location": _hex_to_json(t.location), "terrain": t.terrain.value}
    if t.number is not None:
        d["number"] = t.number
    return d


def _tile_from_json(d: dict) -> Tile:
    return Tile(
        location=_hex_from_json(d["location"]),
        terrain=Terrain(d["terrain"]),
        number=d.get("number"),
    )


def _port_to_json(p: Port) -> dict:
    d: dict[str, Any] = {
        "vertices": [_vertex_to_json(p.vertices[0]), _vertex_to_json(p.vertices[1])],
        "rate": p.rate,
    }
    if p.resource is not None:
        d["resource"] = p.resource.value
    return d


def _port_from_json(d: dict) -> Port:
    return Port(
        vertices=(_vertex_from_json(d["vertices"][0]), _vertex_from_json(d["vertices"][1])),
        rate=d["rate"],
        resource=Resource(d["resource"]) if d.get("resource") else None,
    )


def _building_to_json(b: VertexBuilding) -> dict:
    return {"vertex": _vertex_to_json(b.vertex), "player": b.player.value}


def _building_from_json(d: dict) -> VertexBuilding:
    return VertexBuilding(vertex=_vertex_from_json(d["vertex"]), player=PlayerColor(d["player"]))


def _road_to_json(r: Road) -> dict:
    return {"vertices": _edge_to_json(r.edge), "player": r.player.value}


def _road_from_json(d: dict) -> Road:
    return Road(edge=_edge_from_json(d["vertices"]), player=PlayerColor(d["player"]))


def _board_to_json(b: Board) -> dict:
    d: dict[str, Any] = {
        "tiles": [_tile_to_json(t) for t in b.tiles],
        "ports": [_port_to_json(p) for p in b.ports],
    }
    if b.robber is not None:
        d["robber"] = _hex_to_json(b.robber)
    if b.settlements:
        d["settlements"] = [_building_to_json(s) for s in b.settlements]
    if b.cities:
        d["cities"] = [_building_to_json(c) for c in b.cities]
    if b.roads:
        d["roads"] = [_road_to_json(r) for r in b.roads]
    return d


def _board_from_json(d: dict) -> Board:
    return Board(
        tiles=[_tile_from_json(t) for t in d["tiles"]],
        ports=[_port_from_json(p) for p in d["ports"]],
        robber=_hex_from_json(d["robber"]) if d.get("robber") else None,
        settlements=[_building_from_json(s) for s in d.get("settlements", [])],
        cities=[_building_from_json(c) for c in d.get("cities", [])],
        roads=[_road_from_json(r) for r in d.get("roads", [])],
    )


