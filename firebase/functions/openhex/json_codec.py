def to_json(obj: Any) -> dict | list | str:
    """Serialize an OpenHex object to a JSON-compatible dict."""
    if isinstance(obj, GameState):
        return _state_to_json(obj)
    if isinstance(obj, Board):
        return _board_to_json(obj)
    if isinstance(obj, GameConfig):
        return _config_to_json(obj)
    if isinstance(obj, Action):
        return _action_to_json(obj)
    if isinstance(obj, Event):
        return _event_to_json(obj)
    if isinstance(obj, PlayerState):
        return _player_to_json(obj)
    raise TypeError(f"Cannot serialize {type(obj)}")


def from_json(d: dict, cls: type) -> Any:
    """Deserialize a JSON dict to an OpenHex object."""
    if cls is GameState:
        return _state_from_json(d)
    if cls is Board:
        return _board_from_json(d)
    if cls is GameConfig:
        return _config_from_json(d)
    if cls is Action:
        return _action_from_json(d)
    if cls is Event:
        return _event_from_json(d)
    if cls is PlayerState:
        return _player_from_json(d)
    raise TypeError(f"Cannot deserialize to {cls}")


def game_log_to_json(config: GameConfig, board: Board, turn_order: list[PlayerColor],
                     events: list[Event]) -> dict:
    """Create a game log JSON object."""
    return {
        "openhex": "0.1",
        "config": _config_to_json(config),
        "board": _board_to_json(Board(tiles=board.tiles, ports=board.ports, robber=board.robber)),
        "turnOrder": [c.value for c in turn_order],
        "events": [_event_to_json(e) for e in events],
    }


def game_log_from_json(d: dict) -> tuple[GameConfig, Board, list[PlayerColor], list[Event]]:
    """Parse a game log JSON object."""
    config = _config_from_json(d["config"])
    board = _board_from_json(d["board"])
    turn_order = [PlayerColor(c) for c in d["turnOrder"]]
    events = [_event_from_json(e) for e in d["events"]]
    return config, board, turn_order, events
