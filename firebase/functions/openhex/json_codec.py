def _state_to_json(s: GameState) -> dict:
    d: dict[str, Any] = {
        "config": _config_to_json(s.config),
        "board": _board_to_json(s.board),
        "bank": _resource_map_to_json(s.bank),
        "devCardDeck": _devcard_map_to_json(s.dev_card_deck),
        "players": [_player_to_json(p) for p in s.players],
        "currentPlayer": s.current_player.value if s.current_player else None,
        "turnOrder": [c.value for c in s.turn_order],
        "turnNumber": s.turn_number,
        "isSetupPhase": s.is_setup_phase,
        "dice": _dice_to_json(s.dice),
        "pendingAction": _pending_to_json(s.pending_action),
        "playedDevCardThisTurn": s.played_dev_card_this_turn,
        "trades": [_trade_to_json(t) for t in s.trades],
        "tradesProposedThisTurn": s.trades_proposed_this_turn,
        "longestRoadPlayer": s.longest_road_player.value if s.longest_road_player else None,
        "largestArmyPlayer": s.largest_army_player.value if s.largest_army_player else None,
        "winner": s.winner.value if s.winner else None,
        "nextTradeId": s.next_trade_id,
        "setupRound": s.setup_round,
        "setupIndex": s.setup_index,
        "setupPlacedSettlement": s.setup_placed_settlement,
    }
    if s.last_setup_settlement:
        d["lastSetupSettlement"] = _vertex_to_json(s.last_setup_settlement)
    if s.balanced_dice is not None:
        d["balancedDice"] = {
            "deck": [list(card) for card in s.balanced_dice.deck],
            "recentRolls": list(s.balanced_dice.recent_rolls),
            "sevensByPlayer": dict(s.balanced_dice.sevens_by_player),
            "sevenStreakPlayer": s.balanced_dice.seven_streak_player,
            "sevenStreakCount": s.balanced_dice.seven_streak_count,
        }
    return d


def _state_from_json(d: dict) -> GameState:
    config = _config_from_json(d["config"])
    bd = None
    if d.get("balancedDice"):
        bd_data = d["balancedDice"]
        bd = BalancedDice(
            # Per-player views omit the deck (SPEC section 11)
            deck=[tuple(c) for c in bd_data.get("deck", [])],
            recent_rolls=bd_data.get("recentRolls", []),
            sevens_by_player=bd_data.get("sevensByPlayer", {}),
            seven_streak_player=bd_data.get("sevenStreakPlayer"),
            seven_streak_count=bd_data.get("sevenStreakCount", 0),
        )
    elif config.dice_mode == DiceMode.BALANCED:
        # A balanced game always carries its deck; an empty one is shuffled
        # on the first draw. Without this, a state that went through JSON
        # before the first roll came back rolling independent dice.
        bd = BalancedDice()
    return GameState(
        config=config,
        board=_board_from_json(d["board"]),
        bank=_resource_map_from_json(d.get("bank", {})),
        dev_card_deck=_devcard_map_from_json(d.get("devCardDeck", {})),
        players=[_player_from_json(p) for p in d.get("players", [])],
        current_player=PlayerColor(d["currentPlayer"]) if d.get("currentPlayer") else None,
        turn_order=[PlayerColor(c) for c in d.get("turnOrder", [])],
        turn_number=d.get("turnNumber", 0),
        is_setup_phase=d.get("isSetupPhase", True),
        dice=_dice_from_json(d.get("dice")),
        pending_action=_pending_from_json(d.get("pendingAction")),
        played_dev_card_this_turn=d.get("playedDevCardThisTurn", False),
        trades=[_trade_from_json(t) for t in d.get("trades", [])],
        trades_proposed_this_turn=d.get("tradesProposedThisTurn", 0),
        longest_road_player=PlayerColor(d["longestRoadPlayer"]) if d.get("longestRoadPlayer") else None,
        largest_army_player=PlayerColor(d["largestArmyPlayer"]) if d.get("largestArmyPlayer") else None,
        winner=PlayerColor(d["winner"]) if d.get("winner") else None,
        balanced_dice=bd,
        next_trade_id=d.get("nextTradeId", 1),
        setup_round=d.get("setupRound", 1),
        setup_index=d.get("setupIndex", 0),
        setup_placed_settlement=d.get("setupPlacedSettlement", False),
        last_setup_settlement=_vertex_from_json(d["lastSetupSettlement"]) if d.get("lastSetupSettlement") else None,
    )


