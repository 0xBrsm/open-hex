def _config_to_json(c: GameConfig) -> dict:
    return {
        "victoryPoints": c.victory_points,
        "discardLimit": c.discard_limit,
        "numPlayers": c.num_players,
        "robberMode": c.robber_mode.value,
        "diceMode": c.dice_mode.value,
        "maxSettlements": c.max_settlements,
        "maxCities": c.max_cities,
        "maxRoads": c.max_roads,
    }


def _config_from_json(d: dict) -> GameConfig:
    return GameConfig(
        victory_points=d.get("victoryPoints", 10),
        discard_limit=d.get("discardLimit", 7),
        num_players=d.get("numPlayers", 4),
        robber_mode=RobberMode(d.get("robberMode", "normal")),
        dice_mode=DiceMode(d.get("diceMode", "random")),
        max_settlements=d.get("maxSettlements", 5),
        max_cities=d.get("maxCities", 4),
        max_roads=d.get("maxRoads", 15),
    )


def _pending_to_json(p: PendingAction | None) -> dict | None:
    if p is None:
        return None
    d: dict[str, Any] = {"type": p.type}
    if p.players:
        d["players"] = {c.value: n for c, n in p.players.items()}
    if p.location:
        d["location"] = _hex_to_json(p.location)
    if p.targets:
        d["targets"] = [c.value for c in p.targets]
    if p.remaining is not None:
        d["remaining"] = p.remaining
    return d


def _pending_from_json(d: dict | None) -> PendingAction | None:
    if d is None:
        return None
    return PendingAction(
        type=d["type"],
        players={PlayerColor(k): v for k, v in d["players"].items()} if d.get("players") else None,
        location=_hex_from_json(d["location"]) if d.get("location") else None,
        targets=[PlayerColor(c) for c in d["targets"]] if d.get("targets") else None,
        remaining=d.get("remaining"),
    )


def _trade_to_json(t: Trade) -> dict:
    return {
        "tradeId": t.trade_id,
        "proposer": t.proposer.value,
        "offering": _resource_map_to_json(t.offering),
        "requesting": _resource_map_to_json(t.requesting),
        "accepting": [c.value for c in t.accepting],
        "rejected": [c.value for c in t.rejected],
    }


def _trade_from_json(d: dict) -> Trade:
    return Trade(
        trade_id=d["tradeId"],
        proposer=PlayerColor(d["proposer"]),
        offering=_resource_map_from_json(d["offering"]),
        requesting=_resource_map_from_json(d["requesting"]),
        accepting=[PlayerColor(c) for c in d.get("accepting", [])],
        rejected=[PlayerColor(c) for c in d.get("rejected", [])],
    )


def _dice_to_json(d: DiceResult | None) -> dict | None:
    if d is None:
        return None
    return {"die1": d.die1, "die2": d.die2}


def _dice_from_json(d: dict | None) -> DiceResult | None:
    if d is None:
        return None
    return DiceResult(die1=d["die1"], die2=d["die2"])


